"""
Rebuilds the service-area ZIP codes from tools/service-cities.txt, using US Census 2020 data:
  assets/js/service-area.js  ZIP -> city, for the booking pages' first question
  backend/ServiceZips.gs     ZIP -> [lat, lon, city], for the booking backend (out-of-area check and
                             drive-time estimates when Google Maps isn't available)

    py tools/build_service_area.py        (add -v to list the ZIPs found for each city)

A ZIP is included when at least 5% of its land is inside one of the listed cities,
or when it holds at least 25% of a listed city (so small towns inside big ZIPs count).
City names must match Census place names in California (cities and CDPs such as
"Highgrove" or "Rowland Heights"); any name it can't find is reported and the
files are not written.
"""
import csv, io, os, sys, tempfile, urllib.request, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CENSUS_URL = "https://www2.census.gov/geo/docs/maps-data/data/rel2020/zcta520/tab20_zcta520_place20_natl.txt"
CACHE = os.path.join(tempfile.gettempdir(), "tab20_zcta520_place20_natl.txt")
GAZ_URL = "https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2020_Gazetteer/2020_Gaz_zcta_national.zip"
GAZ_CACHE = os.path.join(tempfile.gettempdir(), "2020_Gaz_zcta_national.zip")
MIN_SHARE = 0.05        # at least 5% of the ZIP is inside the city, or
MIN_PLACE_SHARE = 0.25  # the ZIP holds at least 25% of the city


def short(name):
    for suf in (" city", " CDP", " town"):
        if name.endswith(suf):
            return name[: -len(suf)]
    return name


def main():
    lines = open(os.path.join(ROOT, "tools", "service-cities.txt"), encoding="utf-8").read().splitlines()
    cities = [l.strip() for l in lines if l.strip() and not l.startswith("#")]
    if not os.path.exists(CACHE):
        print("Downloading Census ZIP/city file (about 10 MB)...")
        urllib.request.urlretrieve(CENSUS_URL, CACHE)

    best, seen, per_city = {}, set(), {c: set() for c in cities}
    for r in csv.DictReader(io.open(CACHE, encoding="utf-8-sig"), delimiter="|"):
        if not r["GEOID_ZCTA5_20"] or not r["GEOID_PLACE_20"].startswith("06"):
            continue
        name = short(r["NAMELSAD_PLACE_20"])
        if name not in per_city:
            continue
        seen.add(name)
        land = int(r["AREALAND_ZCTA5_20"] or 0)
        place_land = int(r["AREALAND_PLACE_20"] or 0)
        part = int(r["AREALAND_PART"] or 0)
        if not land:
            continue
        share = part / land
        place_share = part / place_land if place_land else 0
        if share < MIN_SHARE and place_share < MIN_PLACE_SHARE:
            continue
        z = r["GEOID_ZCTA5_20"]
        per_city[name].add(z)
        if z not in best or share > best[z][1]:   # label each ZIP with the city covering most of it
            best[z] = (name, share)

    missing = [c for c in cities if c not in seen]
    if missing:
        sys.exit("Not found as California Census places (check spelling): " + ", ".join(missing))
    no_zip = [c for c in cities if not per_city[c]]

    body = ",\n".join('  "%s": "%s"' % (z, best[z][0]) for z in sorted(best))
    out = ("/*\n  ZIP codes we serve, and the city each one belongs to (the booking pages' first question).\n"
           "  GENERATED by tools/build_service_area.py from tools/service-cities.txt; do not edit by hand.\n"
           "  A ZIP is included when at least 5%% of its land is inside one of the cities,\n"
           "  or when it holds at least 25%% of a city.\n"
           "  Cities (%d): %s.\n*/\nwindow.DGB_SERVICE_ZIPS = {\n%s\n};\n") % (len(cities), ", ".join(cities), body)
    open(os.path.join(ROOT, "assets", "js", "service-area.js"), "w", encoding="utf-8", newline="\n").write(out)
    print("%d cities -> %d ZIP codes written to assets/js/service-area.js" % (len(cities), len(best)))
    if no_zip:
        print("WARNING, no ZIP found for: " + ", ".join(no_zip))

    # ZIP centre points for the backend
    if not os.path.exists(GAZ_CACHE):
        print("Downloading Census ZIP locations (about 1 MB)...")
        urllib.request.urlretrieve(GAZ_URL, GAZ_CACHE)
    zf = zipfile.ZipFile(GAZ_CACHE)
    text = zf.read([n for n in zf.namelist() if n.endswith(".txt")][0]).decode("utf-8-sig")
    points = {}
    for r in csv.DictReader(io.StringIO(text), delimiter="\t"):
        r = {k.strip(): (v or "").strip() for k, v in r.items()}
        if r["GEOID"] in best:
            points[r["GEOID"]] = (float(r["INTPTLAT"]), float(r["INTPTLONG"]))
    lost = sorted(z for z in best if z not in points)
    if lost:   # campuses / PO-box style ZIPs: still served, just no centre point
        print("Note, no Census location for (kept, location empty): " + ", ".join(lost))
    rows = ",\n".join(('  "%s": [%.5f, %.5f, "%s"]' % (z, points[z][0], points[z][1], best[z][0])) if z in points
                      else ('  "%s": [null, null, "%s"]' % (z, best[z][0])) for z in sorted(best))
    gs = ("/**\n * ZIP codes we serve: [latitude, longitude, city] (ZIP centre points, US Census 2020).\n"
          " * GENERATED by tools/build_service_area.py from tools/service-cities.txt; do not edit by hand.\n"
          " * Paste into the Apps Script project as a second file next to Code.gs.\n */\n"
          "var SERVICE_ZIPS = {\n%s\n};\n") % rows
    open(os.path.join(ROOT, "backend", "ServiceZips.gs"), "w", encoding="utf-8", newline="\n").write(gs)
    print("%d ZIPs (%d with a location) written to backend/ServiceZips.gs" % (len(best), len(points)))

    if "-v" in sys.argv:
        for c in cities:
            print("  %-22s %s" % (c, " ".join(sorted(per_city[c]))))


if __name__ == "__main__":
    main()
